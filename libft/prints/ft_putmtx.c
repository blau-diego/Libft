#include "../libft.h"

void	ft_putmtx(char **mtx)
{
	int	i;
	int	j;

	i = 0;
	while (mtx[i])
	{
		j = 0;
		while(mtx[i][j])
		{
			write(1, &mtx[i][j], 1);
			j++;
		}
		write(1, "\n", 1);
	}
}
